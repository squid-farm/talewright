using Talewright.Core.Identity;
using Talewright.Narrative.Templates;

namespace Talewright.Narrative.Rendering;

/// <summary>
/// Presentation-agnostic output of the template renderer: fully resolved text with styling and placeholders.
/// The Blazor player turns this into HTML; a console or game-engine front end could render it differently.
/// </summary>
public sealed record RenderedDocument(IReadOnlyList<RenderedBlock> Blocks)
{
    public static RenderedDocument Empty { get; } = new([]);

    /// <summary>Plain-text form (styles dropped), handy for tests, logs and accessibility.</summary>
    public string ToPlainText() => string.Join("\n\n", Blocks.Select(b => b.ToPlainText()));
}

public abstract record RenderedBlock
{
    public abstract string ToPlainText();
}

public sealed record RenderedParagraph(IReadOnlyList<RenderedInline> Inlines) : RenderedBlock
{
    public override string ToPlainText() => RenderedInline.ToPlainText(Inlines);
}

public sealed record RenderedSpeech(EntityId Speaker, string SpeakerName, IReadOnlyList<RenderedInline> Inlines) : RenderedBlock
{
    public override string ToPlainText() => $"{SpeakerName}: {RenderedInline.ToPlainText(Inlines)}";
}

public enum NoteKind
{
    /// <summary>Skill check outcome.</summary>
    Check,

    /// <summary>Stat, item or faction change worth telling the player about.</summary>
    Change,

    Info,
}

/// <summary>A system message (dice results, "Gained: Relic of Ysh"). Generated by the runtime, not authored.</summary>
public sealed record RenderedNote(NoteKind Kind, string Text) : RenderedBlock
{
    public override string ToPlainText() => $"[{Text}]";
}

public abstract record RenderedInline
{
    public static string ToPlainText(IEnumerable<RenderedInline> inlines) =>
        string.Concat(inlines.Select(i => i switch
        {
            RenderedText t => t.Text,
            RenderedLineBreak => "\n",
            _ => string.Empty,
        }));
}

public sealed record RenderedText(string Text, TextStyle Style) : RenderedInline;

public sealed record RenderedLineBreak : RenderedInline;

/// <summary>Resolved image identity, effective alt text and inherited presentation style; no asset I/O.</summary>
public sealed record RenderedMedia(string MediaId, string AltText) : RenderedInline
{
    public TextStyle Style { get; init; }
}
